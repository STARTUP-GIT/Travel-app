const upsertStateWithDistricts = async (
  countryId: string,
  stateName: string,
  districtNames: string[]
) => {
  let state = await prisma.state.findFirst({
    where: {
      name: stateName,
      countryId,
    },
  });

  if (!state) {
    state = await prisma.state.create({
      data: {
        name: stateName,
        countryId,
        isServiceAvailable: false,
      },
    });
  }

  for (const districtName of districtNames) {
    let district = await prisma.district.findFirst({
      where: {
        name: districtName,
        stateId: state.id,
      },
    });

    if (!district) {
      await prisma.district.create({
        data: {
          name: districtName,
          stateId: state.id,
          isServiceAvailable: false,
        },
      });
    }
  }
};

const main = async () => {
  let india = await prisma.country.findFirst({
    where: {
      name: INDIA_NAME,
    },
  });

  if (!india) {
    india = await prisma.country.create({
      data: {
        name: INDIA_NAME,
        isServiceAvailable: true,
      },
    });
  }

  for (const state of geoData) {
    await upsertStateWithDistricts(india.id, state.name, state.districts);
  }

  console.log("Geographic data seeded successfully.");
};

main()
  .catch((error) => {
    console.error("Seed error:", error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });